import { hasStarGroup, resolvePolicy } from "../policy/index.js";

export const GENERATED_HEADER = "# Generated by web-threshold";

function group(names: string[], rule: string): string {
  return [...names.map((name) => `User-agent: ${name}`), rule].join("\n");
}

/** Turns a config into robots.txt text. `extra` is copied as written, never normalised. */
export function generateRobots(config: unknown): string {
  const { preset, blocked, allowed, extra } = resolvePolicy(config);
  const groups: string[] = [];

  if (preset === "search-engines-only") {
    groups.push(group(["*"], "Disallow: /"));
    if (allowed.length > 0) groups.push(group(allowed, "Allow: /"));
  } else if (preset === "open" && !(extra !== undefined && hasStarGroup(extra))) {
    groups.push(group(["*"], "Allow: /"));
  }
  // Under search-engines-only, `*` already refuses them, except a name in `block`
  // that is also a search engine, which simply drops out of `allowed`.
  if (preset !== "search-engines-only" && blocked.length > 0) {
    groups.push(group(blocked, "Disallow: /"));
  }

  const generated = groups.join("\n\n");
  if (extra === undefined) return `${GENERATED_HEADER}\n${generated}\n`;
  return generated ? `${GENERATED_HEADER}\n${generated}\n\n${extra}` : `${GENERATED_HEADER}\n${extra}`;
}
