import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { GENERATED_HEADER, generateRobots } from "../robots/index.js";
import { seal } from "../seal/index.js";

const CONFIG = "threshold.config.ts";
const OUT = join("public", "robots.txt");
const USAGE = "usage: web-threshold robots\n       web-threshold seal --doors <file> --out <dir> [--shell <file>] [--public-fixture]";

/** Why Node couldn't load a `.ts` config, in words a site owner can act on. */
function loadFailure(err: unknown): string {
  const code = (err as { code?: string }).code;
  if (code === "ERR_UNKNOWN_FILE_EXTENSION") {
    return `this Node can't load ${CONFIG}; it needs a Node with type stripping turned on (Node 24 has it)`;
  }
  if (err instanceof SyntaxError) {
    return `${CONFIG} didn't load as an ES module (${err.message}); check "type" in the site's package.json is not "commonjs"`;
  }
  return `${CONFIG} didn't load: ${err instanceof Error ? err.message : String(err)}`;
}

async function robots(cwd: string, log: (line: string) => void): Promise<number> {
  const configPath = join(cwd, CONFIG);
  if (!existsSync(configPath)) {
    log(`no ${CONFIG} in ${cwd}`);
    return 1;
  }

  let config: unknown;
  try {
    config = ((await import(pathToFileURL(configPath).href)) as { default?: unknown }).default;
  } catch (err) {
    // defineThreshold() throws while the config loads, from the package's policy.js:
    // a different copy of the class than this bundle's, so compare by name.
    const invalid = (err as Error | undefined)?.name === "ThresholdConfigError";
    log(invalid ? `${CONFIG}:\n${(err as Error).message}` : loadFailure(err));
    return 1;
  }
  if (config === undefined) {
    log(`${CONFIG} has no default export`);
    return 1;
  }

  let text: string;
  try {
    text = generateRobots(config);
  } catch (err) {
    log(`${CONFIG}:\n${err instanceof Error ? err.message : String(err)}`);
    return 1;
  }

  const outPath = join(cwd, OUT);
  if (existsSync(outPath) && !readFileSync(outPath, "utf8").startsWith(GENERATED_HEADER)) {
    log(`${OUT} wasn't generated by web-threshold, so it stays. To replace it: git rm ${OUT}, moving any rules you need into extra`);
    return 1;
  }
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, text);
  log(`wrote ${OUT}`);
  return 0;
}

interface SealArgs {
  doors: string;
  out: string;
  shell?: string;
  publicFixture: boolean;
}

/** Strict on purpose: a phrase must never be passed here, and a typo must not be ignored. */
function sealArgs(args: string[]): SealArgs | null {
  const parsed: Partial<SealArgs> = { publicFixture: false };
  for (let index = 0; index < args.length; index++) {
    const arg = args[index];
    if (arg === "--public-fixture") parsed.publicFixture = true;
    else if (arg === "--doors" || arg === "--out" || arg === "--shell") {
      const value = args[++index];
      if (value === undefined) return null;
      parsed[arg.slice(2) as "doors" | "out" | "shell"] = value;
    } else return null;
  }
  return parsed.doors && parsed.out ? (parsed as SealArgs) : null;
}

/** The built element, beside this file in dist/, which shells inline. */
function builtElement(): string | undefined {
  const url = new URL("./web-threshold-sealed.js", import.meta.url);
  return url.protocol === "file:" && existsSync(url) ? readFileSync(url, "utf8") : undefined;
}

function runSeal(options: SealArgs, cwd: string, log: (line: string) => void): Promise<number> {
  return seal({
    doors: resolve(cwd, options.doors),
    out: resolve(cwd, options.out),
    publicFixture: options.publicFixture,
    log,
    ...(options.shell ? { shell: resolve(cwd, options.shell) } : {}),
    ...(builtElement() ? { element: builtElement()! } : {}),
  });
}

/** Returns the process exit code. */
export async function run(
  args: string[],
  cwd: string,
  log: (line: string) => void = console.error,
): Promise<number> {
  if (args.length === 1 && args[0] === "robots") return robots(cwd, log);
  if (args[0] === "seal") {
    const options = sealArgs(args.slice(1));
    if (options) return runSeal(options, cwd, log);
  }
  log(USAGE);
  return 1;
}
